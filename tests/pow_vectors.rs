/// `fpow` at `f64` (function 0), `fpow` at `f32` (function 1), and `dpow`
/// on dynamic floats (function 2).
fn program() -> Program {
    let mut m = ModuleBuilder::new();
    let mut f = m.function("pow64", &[ValType::F64, ValType::F64], &[ValType::F64]);
    let r = f.reg(ValType::F64);
    f.emit(Inst::FPow {
        dst: r,
        lhs: Reg(0),
        rhs: Reg(1),
        ty: FloatTy::F64,
    });
    f.ret(r);
    m.add_function(f).unwrap();
    let mut f = m.function("pow32", &[ValType::F32, ValType::F32], &[ValType::F32]);
    let r = f.reg(ValType::F32);
    f.emit(Inst::FPow {
        dst: r,
        lhs: Reg(0),
        rhs: Reg(1),
        ty: FloatTy::F32,
    });
    f.ret(r);
    m.add_function(f).unwrap();
    let mut f = m.function("dpow", &[ValType::Dyn, ValType::Dyn], &[ValType::Dyn]);
    let r = f.reg(ValType::Dyn);
    f.emit(Inst::DPow {
        dst: r,
        lhs: Reg(0),
        rhs: Reg(1),
        pol: Default::default(),
    });
    f.ret(r);
    m.add_function(f).unwrap();
    load(m.finish().unwrap())
}

#[test]
fn fpow_f64_matches_every_vector_bit_for_bit() {
    let p = program();
    let mut vm = Vm::new(&p);
    for (i, &(x, y, want)) in VECTORS.iter().enumerate() {
        let args = [
            Value::Float(f64::from_bits(x)),
            Value::Float(f64::from_bits(y)),
        ];
        let got = match vm.run(bytecode_lang::FuncId(0), &args) {
            Ok(Value::Float(r)) => r.to_bits(),
            other => panic!("vector {}: {other:?}", i + 1),
        };
        assert_eq!(got, want, "vector {}: {x:#018x} ** {y:#018x}", i + 1);
    }
}

#[test]
fn dpow_on_floats_takes_the_same_routine() {
    let p = program();
    let mut vm = Vm::new(&p);
    for (i, &(x, y, want)) in VECTORS.iter().enumerate() {
        let (xf, yf) = (f64::from_bits(x), f64::from_bits(y));
        let args = [Value::Float(xf), Value::Float(yf)];
        let got = match vm.run(bytecode_lang::FuncId(2), &args) {
            Ok(Value::Float(r)) => r.to_bits(),
            other => panic!("vector {}: {other:?}", i + 1),
        };
        // A dynamic NaN is the canonical one; every other result is the row.
        let want = if f64::from_bits(want).is_nan() {
            0x7FF8_0000_0000_0000
        } else {
            want
        };
        assert_eq!(got, want, "vector {}", i + 1);
    }
}

#[test]
fn fpow_f32_is_ls_pow_of_the_widened_operands_rounded_once() {
    let p = program();
    let mut vm = Vm::new(&p);
    // Every row whose operands are exact f32 values: the f32 result is the
    // f64 row rounded once.
    let mut checked = 0;
    for &(x, y, want) in VECTORS {
        let (xf, yf) = (f64::from_bits(x), f64::from_bits(y));
        let (x32, y32) = (xf as f32, yf as f32);
        if f64::from(x32).to_bits() != x || f64::from(y32).to_bits() != y {
            continue;
        }
        let got = match vm.run(
            bytecode_lang::FuncId(1),
            &[Value::F32(x32), Value::F32(y32)],
        ) {
            Ok(Value::F32(r)) => r,
            other => panic!("{other:?}"),
        };
        let expect = f64::from_bits(want) as f32;
        assert!(
            got.to_bits() == expect.to_bits() || (got.is_nan() && expect.is_nan()),
            "{xf} ** {yf}: {got} vs {expect}"
        );
        checked += 1;
    }
    assert!(checked >= 60, "only {checked} rows are exact in f32");
    // 3^0.5 in f32: ls_pow(3, 0.5) = 1.7320508075688772 rounds to 1.7320508.
    let got = vm.run(
        bytecode_lang::FuncId(1),
        &[Value::F32(3.0), Value::F32(0.5)],
    );
    assert_eq!(got, Ok(Value::F32(1.732_050_8)));
}
